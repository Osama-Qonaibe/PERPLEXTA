export const getLocalizedContent = (
  section: keyof typeof CORE_PROTOCOL,
  lang: "ar" | "en"
) => {
  const data = CORE_PROTOCOL[section];
  if (typeof data === "object" && data !== null) {
    const result: Record<string, string> = {};
    for (const [key, value] of Object.entries(data)) {
      if (typeof value === "object" && value !== null && "ar" in value && "en" in value) {
        result[key] = value[lang];
      }
    }
    return result;
  }
  return null;
};

export const validateProtocol = () => {
  const requiredSections = ["identity", "response", "tools", "followups", "security"];
  const missingSections = requiredSections.filter(
    (section) => !(section in CORE_PROTOCOL)
  );
  
  if (missingSections.length > 0) {
    throw new Error(`Missing required sections: ${missingSections.join(", ")}`);
  }

  const sections = Object.keys(CORE_PROTOCOL).filter(
    (key) => key !== "version" && key !== "lastUpdated" && 
             key !== "restrictions" && key !== "contextRules"
  );

  for (const section of sections) {
    const data = CORE_PROTOCOL[section as keyof typeof CORE_PROTOCOL];
    if (typeof data === "object" && data !== null) {
      for (const [key, value] of Object.entries(data)) {
        if (typeof value === "object" && value !== null && "ar" in value && "en" in value) {
          if (!value.ar || !value.en) {
            throw new Error(`Section "${section}" key "${key}" has empty localized content`);
          }
        }
      }
    }
  }

  return true;
};

